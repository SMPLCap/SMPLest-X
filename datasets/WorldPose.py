import os.path as osp
from datasets.humandata import HumanDataset


class WorldPose(HumanDataset):
    """WorldPose football broadcast dataset — body-only SMPL supervision."""

    def __init__(self, transform, data_split, cfg):
        super(WorldPose, self).__init__(transform, data_split, cfg)

        self.cfg = cfg
        self.use_cache = getattr(self.cfg.data, 'use_cache', False)
        self.annot_path_cache = osp.join(
            self.cfg.data.data_dir, 'cache', f'worldpose_{data_split}.npz'
        )
        self.img_shape = None  # read from meta per-sample
        self.cam_param = {}

        if self.use_cache and osp.isfile(self.annot_path_cache):
            print(f'[{self.__class__.__name__}] Loading cache from {self.annot_path_cache}')
            self.datalist = self.load_cache(self.annot_path_cache)
        else:
            if self.use_cache:
                print(f'[{self.__class__.__name__}] Cache not found, generating...')

            self.datalist = []

            # annot files live in data_dir/annot/worldpose_{split}.npz
            # (generated by solution/worldpose_to_humandata.py)
            filename = f'worldpose_{data_split}.npz'
            self.annot_path = osp.join(self.cfg.data.data_dir, 'annot', filename)
            # img_dir is not used — image_path in the .npz contains absolute paths
            self.img_dir = ''

            self.datalist = self.load_data(
                train_sample_interval=getattr(
                    self.cfg.data, 'WorldPose_train_sample_interval', 1),
                test_sample_interval=getattr(
                    self.cfg.data, 'WorldPose_test_sample_interval', 1),
            )

            if self.use_cache:
                self.save_cache(self.annot_path_cache, self.datalist)
